@pytest.mark.django_db
def test_passive_scan_feeds_the_normal_ingest_pipeline(website):
    """An installed snippet enables the static scan supplement."""
    from apps.common import outbound
    from apps.websites.tasks import passive_scan_website

    Website.objects.filter(pk=website.pk).update(
        snippet_status=Website.SnippetStatus.INSTALLED
    )

    html = (
        "<html><head><script src='https://cdn.example.com/a.js'></script>"
        "</head><body>x</body></html>"
    )
    result = outbound.FetchResult(
        status_code=200, body=html, headers={}, elapsed_ms=10,
        final_url="https://passive.test/",
    )

    with patch("apps.websites.tasks.outbound.fetch", return_value=result), \
         patch("apps.scripts.tasks.process_ingest_payload.delay") as ingest:
        passive_scan_website(str(website.pk))

    ingest.assert_called_once()
    payload = ingest.call_args.args[1]
    assert payload["scripts"][0]["src"] == "https://cdn.example.com/a.js"
    assert payload["snippet_version"] == "server-scan"


@pytest.mark.django_db
def test_passive_scan_records_a_block_without_wiping_state(website):
    """A WAF serving us its block page is not evidence the site has no scripts."""
    from apps.common import outbound
    from apps.websites.tasks import passive_scan_website

    Website.objects.filter(pk=website.pk).update(
        snippet_status=Website.SnippetStatus.INSTALLED
    )

    blocked = outbound.FetchResult(
        status_code=403, body="Generated by Wordfence", headers={}, elapsed_ms=5,
        final_url="https://passive.test/",
    )

    with patch("apps.websites.tasks.outbound.fetch", return_value=blocked), \
         patch("apps.scripts.tasks.process_ingest_payload.delay") as ingest:
        passive_scan_website(str(website.pk))

    ingest.assert_not_called()
    state = SiteScanState.objects.get(website=website)
    assert "wordfence" in state.error.lower()


