"""check_http result classification.

Covers the ways a reachable site was being misreported as a hard outage: WAF
blocks from every vendor except the two that were special-cased, a non-2xx
`expected_status_code` that could never match, and transport errors collapsed
into an unactionable message.

Mocking note: check_http goes through `apps.common.outbound`, so these tests
patch that module's guarded opener rather than `urllib.request.urlopen`. That
keeps the SSRF guard, the redirect handler and the backoff bookkeeping in the
path under test instead of stubbing them out.
"""

import io
import socket
import ssl
import urllib.error
from email.message import Message
from unittest.mock import MagicMock, patch

import pytest
from django.core.cache import cache

from apps.common import outbound
from apps.monitors.checker import check_http

URL = "https://example.com"


@pytest.fixture(autouse=True)
def _no_ssrf_or_backoff(monkeypatch):
    """example.com must not be DNS-resolved, and state must not leak between tests."""
    monkeypatch.setattr(outbound, "assert_public_url", lambda url: None)
    cache.clear()
    yield
    cache.clear()


def headers(**kwargs):
    m = Message()
    for k, v in kwargs.items():
        m[k.replace("_", "-")] = v
    return m


def http_error(code, body=b"", **hdrs):
    return urllib.error.HTTPError(
        URL, code, f"HTTP Error {code}", headers(**hdrs), io.BytesIO(body)
    )


def ok_response(status=200, body=b"hello world", **hdrs):
    resp = MagicMock()
    resp.status = status
    resp.getcode.return_value = status
    resp.read.return_value = body
    resp.headers = headers(**hdrs)
    resp.geturl.return_value = URL
    resp.__enter__ = lambda s: s
    resp.__exit__ = lambda s, *a: False
    return resp


def opening(*responses):
    """Patch the guarded opener to yield each response/exception in turn."""
    calls = []

    def _open(req, timeout=None):
        calls.append(req)
        item = responses[min(len(calls) - 1, len(responses) - 1)]
        if isinstance(item, Exception):
            raise item
        return item

    fake = MagicMock()
    fake.open = _open
    ctx = patch.object(outbound, "_opener", lambda: fake)
    ctx.calls = calls
    return ctx, calls


# --- WAF blocks are not outages -------------------------------------------


@pytest.mark.parametrize(
    "hdrs,body,vendor",
    [
        ({"cf_mitigated": "challenge", "server": "cloudflare"}, b"", "cloudflare"),
        ({"server": "cloudflare"}, b"", "cloudflare"),
        ({"x_sucuri_block": "1"}, b"", "sucuri"),
        ({"x_imunify360_request_id": "abc"}, b"", "imunify360"),
        ({"x_amzn_waf_action": "block"}, b"", "aws waf"),
        ({"server": "nginx"}, b"Generated by Wordfence", "wordfence"),
        ({"server": "Apache mod_security"}, b"", "modsecurity"),
    ],
)
def test_named_waf_403_is_blocked_not_down(hdrs, body, vendor):
    ctx, _ = opening(http_error(403, body=body, **hdrs))
    with ctx:
        result = check_http(URL)

    assert result["status"] == "blocked"
    assert result["status_code"] == 403
    assert vendor in result["error_message"].lower()
    assert "allowlist" in result["error_message"].lower()


def test_plain_server_403_is_still_down():
    """An unattributable 403 is a real misconfiguration, not an excuse."""
    body = b"Forbidden, and nothing else at all. " * 60
    ctx, _ = opening(http_error(403, body=body, server="nginx"))
    with ctx:
        result = check_http(URL)

    assert result["status"] == "down"
    assert result["status_code"] == 403


def test_cloudflare_522_stays_down():
    """522 means Cloudflare could not reach the origin — a genuine outage."""
    ctx, _ = opening(http_error(522, server="cloudflare"))
    with ctx:
        result = check_http(URL)

    assert result["status"] == "down"
    assert result["status_code"] == 522
    assert "origin server timed out" in result["error_message"]


def test_cloudflare_fronted_500_is_down_not_blocked():
    """server: cloudflare on a 5xx is the origin failing, not a block."""
    ctx, _ = opening(http_error(500, server="cloudflare"))
    with ctx:
        result = check_http(URL)

    assert result["status"] == "down"


# --- HEAD first, GET when it must -----------------------------------------


def test_first_attempt_uses_head():
    ctx, calls = opening(ok_response())
    with ctx:
        check_http(URL)

    assert calls[0].get_method() == "HEAD"


def test_head_falls_back_to_get_on_405():
    ctx, calls = opening(http_error(405), ok_response())
    with ctx:
        result = check_http(URL)

    assert [c.get_method() for c in calls] == ["HEAD", "GET"]
    assert result["status"] == "up"


def test_head_falls_back_to_get_on_501():
    ctx, calls = opening(http_error(501), ok_response())
    with ctx:
        result = check_http(URL)

    assert [c.get_method() for c in calls] == ["HEAD", "GET"]
    assert result["status"] == "up"


def test_keyword_monitor_always_uses_get():
    """A HEAD has no body to search, so a keyword monitor must never send one."""
    ctx, calls = opening(ok_response(body=b"hello world"))
    with ctx:
        result = check_http(URL, keyword="hello")

    assert calls[0].get_method() == "GET"
    assert result["status"] == "up"


def test_second_attempt_uses_get():
    ctx, calls = opening(ok_response())
    with ctx:
        check_http(URL, attempt=2)

    assert calls[0].get_method() == "GET"


def test_third_attempt_sends_no_cache():
    """Vary the request shape so one WAF rule can't fail all three identically."""
    ctx, calls = opening(ok_response())
    with ctx:
        check_http(URL, attempt=3)

    assert calls[0].get_method() == "GET"
    assert calls[0].get_header("Cache-control") == "no-cache"


def test_requests_carry_the_platform_identity():
    ctx, calls = opening(ok_response())
    with ctx:
        check_http(URL)

    assert calls[0].get_header("User-agent") == outbound.USER_AGENT
    assert "Digivault-Monitor" in calls[0].get_header("User-agent")


